module syndrome_pow(
    input  [5:0]        syn[1:0],
    output reg [5:0]    S[3:0]
);

    always @(*) begin
        S[0][0] = syn[0][0];
        S[0][1] = syn[0][1];
        S[0][2] = syn[0][2];
        S[0][3] = syn[0][3];
        S[0][4] = syn[0][4];
        S[0][5] = syn[0][5];

        S[1][0] = syn[0][0] ^ syn[0][3];
        S[1][1] = syn[0][3];
        S[1][2] = syn[0][1] ^ syn[0][4];
        S[1][3] = syn[0][4];
        S[1][4] = syn[0][2] ^ syn[0][5];
        S[1][5] = syn[0][5];

        S[2][0] = syn[1][0];
        S[2][1] = syn[1][1];
        S[2][2] = syn[1][2];
        S[2][3] = syn[1][3];
        S[2][4] = syn[1][4];
        S[2][5] = syn[1][5];

        S[3][0] = syn[0][0] ^ syn[0][3] ^ syn[0][4];
        S[3][1] = syn[0][4];
        S[3][2] = syn[0][2] ^ syn[0][3] ^ syn[0][5];
        S[3][3] = syn[0][2] ^ syn[0][5];
        S[3][4] = syn[0][1] ^ syn[0][4] ^ syn[0][5];
        S[3][5] = syn[0][5];

    end

endmodule